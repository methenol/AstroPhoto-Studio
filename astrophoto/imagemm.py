"""ImageMM: joint multi-frame image restoration and super-resolution.

Implementation of Sukurdeep, Budavári, Connolly & Navarro (2025), "ImageMM: Joint
Multi-Frame Image Restoration and Super-Resolution", arXiv:2501.03002 (v3).
Equation / algorithm numbers refer to the paper; verification against its own
model: experiments/test_imagemm.py.

Data (Sec. 2): n coregistered, background-subtracted exposures y(t) with
per-pixel variances v(t), binary masks m(t) and PSFs f(t) measured from their
stars (prepared from the raw subs by astrophoto/exposures.py).  Model (Eq. 1, 10):

    y(t)_i = (D (h(t) * x))_i + eta(t)_i,    eta(t)_i ~ N(0, v(t)_i),    x >= 0

x is the latent sky (sky = 0, sources > 0), padded so that every exposure pixel
is fully modelled: r(d + d') - 1 pixels per axis for d exposure pixels and PSFs
of d' pixels (d + d' - 1 without super-resolution); "*" is the valid
convolution; D is r x r average pooling and D^T subdivides every entry into
r x r replicas (Algorithm 2 remark).  Without super-resolution h(t) = f(t).

Algorithms 1 / 2 (Eqs. 7-9):

    u_k  = sum_t H(t)^T D^T W(t) y(t) / sum_t H(t)^T D^T W(t) D H(t) x_{k-1},    W(t) = diag(m(t) / v(t))
    u'_k = max(1/kappa, min(kappa, u_k)),    x_k = x_{k-1} * u'_k

Algorithm 3 (Eqs. 13-18): W(t) becomes m / v * psi(r) with the residuals
r = (y - D H x) / sigma recomputed every iteration and psi(z) = rho'(z)/z of the
Huber loss (Eq. 15, delta = 2).

x0 (Sec. 4.1): the median of the exposures, padded, non-positive values
replaced by a positive one; kappa = 2.  Stop (Appendix C, Eq. C15) when
|(1/M~) sum_i (m~ xi_k)_i - 1| < epsilon with xi_k = u'_k / u'_{k-1} and the
effective mask m~ = [(1/n) sum_t H^T D^T m(t) > mu], mu = 0.1, epsilon in
(1e-6, 1e-4); K is the maximum number of iterations.

Super-resolved PSFs (Eq. 11, Algorithm 2 lines 4-6): h(t) minimises
(1/d') sum_i (f(t)_i - (D(h * g_sigma))_i)^2, unconstrained, by Adam, with g_sigma
a centred Gaussian (2 r d' - 1 pixels per axis) generated by Monte Carlo
integration.

Like the paper (Sec. 5.1), the field is processed in cutouts; here they overlap
and are blended.

Optional, not part of the paper, each implemented to its own reference:
* Biggs & Andrews (1997) vector extrapolation of the multiplicative iteration
  (``BiggsAndrews``);
* seeing groups: inverse-variance coadds of exposures of similar PSF, each a
  single exposure of the same model with the weight-averaged PSF
  (``coadd_groups``);
* Moffat PSF models fitted to the empirical PSFs (exposures.fit_moffat).
"""
